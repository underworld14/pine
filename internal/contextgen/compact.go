// ContextCompact renders the default pine context: a briefing sized for an
// agent's context window — status counts instead of full tables, ready work,
// only the tickets relevant to the current changes, memory, and the write-back
// conventions. Context() keeps the exhaustive layout for --full.
func ContextCompact(s *store.Store, git gitx.Status, now time.Time) string {
	var b strings.Builder
	cfg := s.Config()
	g := s.Graph()
	all := s.List(store.Filter{})
	s.SortByPriorityThenUpdated(all)

	fmt.Fprintf(&b, "# Project Context: %s\n", cfg.Project.Name)
	fmt.Fprintf(&b, "> Generated by Pine · %s (compact — pass --full for every open ticket)\n\n", now.UTC().Format(time.RFC3339))

	// Repository.
	b.WriteString("## Repository\n")
	if git.IsRepo {
		fmt.Fprintf(&b, "- Branch: `%s` · uncommitted changes: %d\n", git.Branch, len(git.Changes))
		if len(git.Changes) > 0 {
			var paths []string
			for _, c := range git.Changes {
				paths = append(paths, c.Path)
			}
			fmt.Fprintf(&b, "- Modified: %s\n", codeList(paths, 5))
		}
	} else {
		b.WriteString("- Not a git repository.\n")
	}
	b.WriteString("\n")

	// Board: one line of counts replaces the open/recently-done/epic tables.
	b.WriteString("## Board\n")
	counts := map[string]int{}
	first := s.Board().FirstStatus()
	for _, t := range all {
		st := t.Status
		if st == "" {
			st = first
		}
		counts[st]++
	}
	parts := make([]string, 0, len(counts))
	for _, st := range s.Board().Statuses() {
		parts = append(parts, fmt.Sprintf("%s: %d", st, counts[st]))
	}
	fmt.Fprintf(&b, "- %s (%d tickets)\n", strings.Join(parts, " · "), len(all))
	b.WriteString("\n")

	// Ready to work — the picking ground.
	var ready []*ticket.Ticket
	for _, t := range all {
		if g.Ready(t.ID) {
			ready = append(ready, t)
		}
	}
	if len(ready) > 0 {
		b.WriteString("## Ready to Work (unblocked)\n")
		writeTable(&b, ready)
		// Skill requirements ride along only when declared, so the compact
		// context stays zero-cost for tickets that name none.
		for _, t := range ready {
			if len(t.Skills) > 0 {
				fmt.Fprintf(&b, "- %s requires skills: %s — load before starting\n", t.ID, codeList(t.Skills, 4))
			}
		}
		b.WriteString("\n")
	}

	// Tickets tied to what changed on this branch right now.
	if hits := relevantHits(git, all, 10); len(hits) > 0 {
		b.WriteString("## Relevant to Current Changes\n")
		for _, h := range hits {
			fmt.Fprintf(&b, "- %s · %s · status: %s · priority: %s — %s\n",
				h.t.ID, mdEscape(h.t.Title), h.t.Status, h.t.Priority, h.why)
		}
		b.WriteString("\n")
	}

	// Work already underway.
	var inFlight []*ticket.Ticket
	for _, t := range all {
		if t.Status == ticket.StatusDoing || t.Status == ticket.StatusTesting {
			inFlight = append(inFlight, t)
		}
	}
	if len(inFlight) > 0 {
		b.WriteString("## In Flight\n")
		for _, t := range inFlight {
			fmt.Fprintf(&b, "- %s · %s · %s\n", t.ID, mdEscape(t.Title), t.Status)
		}
		b.WriteString("\n")
	}

	var cwdHints []string
	for _, c := range git.Changes {
		cwdHints = append(cwdHints, c.Path)
	}
	memBlock := FormatMemoryBlock(s, cwdHints, nil, 2)
	b.WriteString(memBlock)
	learnings, more := SelectLearnings(s, LearningSelectOpts{CwdHints: cwdHints, Limit: 5})
	if block := FormatLearningsBlock(learnings, more); block != "" {
		b.WriteString(block)
	}
	writeConventions(&b, s, memBlock)
	return b.String()
}

// relevantHit pairs a ticket with the reason it is relevant to current changes.
type relevantHit struct {
	t   *ticket.Ticket
	why string
}

// relevantHits returns open tickets whose Related Files intersect the
// uncommitted changes or whose ID a recent commit subject mentions — the
// tickets an agent starting on this branch most likely needs. sorted must be
// priority-ordered (SortByPriorityThenUpdated); limit caps the result.
func relevantHits(git gitx.Status, sorted []*ticket.Ticket, limit int) []relevantHit {
	var changed []string
	for _, c := range git.Changes {
		changed = append(changed, c.Path)
	}
	var out []relevantHit
	for _, t := range sorted {
		if t.Status == ticket.StatusDone || t.Prefix() == "EPIC" {
			continue
		}
		var why []string
		var files []string
		for _, rf := range ticket.RelatedFiles(t.Body) {
			for _, ch := range changed {
				if pathMatches(ch, rf) && !sliceContains(files, ch) {
					files = append(files, ch)
				}
			}
		}
		if len(files) > 0 {
			why = append(why, "changed: "+codeList(files, 3))
		}
		for _, c := range git.Commits {
			if strings.Contains(c.Subject, t.ID) {
				why = append(why, fmt.Sprintf("commit `%s` %s", shortHash(c.Hash), c.Subject))
				break
			}
		}
		if len(why) == 0 {
			continue
		}
		out = append(out, relevantHit{t: t, why: strings.Join(why, "; ")})
		if len(out) >= limit {
			break
		}
	}
	return out
}

// pathMatches reports whether a changed git path falls under a Related Files
// entry. Entries may carry trailing annotations ("file.go (Func)") and may
// name a directory with or without a trailing slash.
func pathMatches(changed, related string) bool {
	if f := strings.Fields(related); len(f) > 0 {
		related = f[0]
	}
	related = strings.Trim(related, "`")
	if related == "" {
		return false
	}
	if changed == related {
		return true
	}
	dir := strings.TrimSuffix(related, "/")
	return strings.HasPrefix(changed, dir+"/")
}

func shortHash(sha string) string {
	if len(sha) > 8 {
		return sha[:8]
	}
	return sha
}

func sliceContains(xs []string, v string) bool {
	for _, x := range xs {
		if x == v {
			return true
		}
	}
	return false
}
